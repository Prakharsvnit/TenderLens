"""Exports: the compliance matrix as XLSX and the draft response as DOCX."""

from __future__ import annotations

import io

from docx import Document
from docx.shared import RGBColor
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill

from .ontology.models import (
    AssessmentBatch,
    BidRecommendation,
    ClaimVerdictLabel,
    ClaimVerdicts,
    DraftMessage,
    RequirementSet,
)

STATUS_FILL = {
    "met": "E5F4E4",
    "partial": "F9EEDA",
    "not_met": "FBEBEB",
    "no_evidence": "F0EFEC",
}


def matrix_xlsx(reqs: RequirementSet, assessed: AssessmentBatch, rec: BidRecommendation | None) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = "Compliance matrix"
    headers = [
        "ID",
        "Page",
        "Category",
        "Obligation",
        "Critical",
        "Requirement",
        "Status",
        "Confidence",
        "Evidence",
        "Rationale",
    ]
    ws.append(headers)
    for cell in ws[1]:
        cell.font = Font(bold=True)
    by_req = {a.requirement_id: a for a in assessed.assessments}
    titles = {e.id: e.doc_title for e in assessed.evidence}
    for r in reqs.requirements:
        a = by_req.get(r.id)
        status = a.status.value if a else "no_evidence"
        ws.append(
            [
                r.id,
                r.page,
                r.category.value,
                r.obligation.value,
                "yes" if r.critical else "",
                r.quote,
                status,
                round(a.confidence, 2) if a else 0,
                "; ".join(f"{e} ({titles.get(e, '')})" for e in (a.evidence_ids if a else [])),
                a.rationale if a else "",
            ]
        )
        ws.cell(row=ws.max_row, column=7).fill = PatternFill("solid", fgColor=STATUS_FILL[status])
    for col, width in zip("ABCDEFGHIJ", [7, 6, 18, 11, 8, 70, 12, 11, 40, 60], strict=True):
        ws.column_dimensions[col].width = width
    for row in ws.iter_rows(min_row=2):
        for cell in row:
            cell.alignment = Alignment(wrap_text=True, vertical="top")

    gaps = wb.create_sheet("Gaps")
    gaps.append(["Requirement", "Severity", "Knock-out", "Gap", "Mitigation"])
    for g in assessed.gaps:
        gaps.append(
            [
                g.requirement_id,
                g.severity.value,
                "yes" if g.knock_out else "",
                g.description,
                f"{g.mitigation.type.value}: {g.mitigation.description}" if g.mitigation else "",
            ]
        )

    if rec:
        d = rec.decision
        sheet = wb.create_sheet("Decision")
        sheet.append(["Decision", d.decision.value])
        sheet.append(["Score", f"{d.score} / {d.max_score} ({d.score_pct:.0%})"])
        sheet.append([])
        sheet.append(["Criterion", "Points", "Status", "Earned"])
        for line in d.score_lines:
            sheet.append([line.criterion, line.points, line.status.value, line.earned])
        sheet.append([])
        sheet.append(["Knock-out", "Outcome", "Fix"])
        for k in d.knock_outs:
            sheet.append([k.description, k.outcome.value, k.fix])
    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()


def draft_docx(
    reqs: RequirementSet, draft: DraftMessage, verdicts: ClaimVerdicts | None, bidder: str
) -> bytes:
    doc = Document()
    doc.add_heading(f"Response to {reqs.rfp.title}", level=0)
    doc.add_paragraph(f"Prepared by {bidder} for {reqs.rfp.buyer.name}. Draft generated by TenderLens.")
    flagged = {
        v.claim_id
        for v in (verdicts.verdicts if verdicts else [])
        if v.verdict != ClaimVerdictLabel.supported
    }
    for section in draft.sections:
        doc.add_heading(section.title, level=1)
        para = doc.add_paragraph()
        for claim in section.claims:
            run = para.add_run(f"{claim.text} ")
            if claim.id in flagged:
                run.font.color.rgb = RGBColor(0xB0, 0x20, 0x20)
            cite = para.add_run(f"[{', '.join(claim.evidence_ids)}] ")
            cite.font.color.rgb = RGBColor(0x80, 0x80, 0x80)
        for placeholder in section.sme_placeholders:
            doc.add_paragraph(f"[SME INPUT NEEDED] {placeholder}", style="List Bullet")
    out = io.BytesIO()
    doc.save(out)
    return out.getvalue()
